#!/usr/bin/env python3
"""Build man/Texinfo/Info manuals from the canonical docs/cli.md reference.

Only a deliberately small Markdown subset is supported: headings, paragraphs,
bullets, fenced examples, and inline backticks. No Python dependencies required.
"""

import argparse
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def blocks(text):
    lines = text.splitlines()
    index = 0
    while index < len(lines):
        line = lines[index]
        index += 1
        if not line.strip():
            continue
        if line.startswith("```"):
            example = []
            while index < len(lines) and not lines[index].startswith("```"):
                example.append(lines[index])
                index += 1
            if index == len(lines):
                raise ValueError("Unclosed fenced example")
            index += 1
            yield "example", "\n".join(example)
        elif line.startswith("#"):
            heading = re.fullmatch(r"(#{1,3}) (.+)", line)
            if not heading:
                raise ValueError("Unsupported heading: " + line)
            yield "heading" + str(len(heading[1])), heading[2]
        elif line.startswith("* "):
            items = []
            while True:
                item = [line[2:]]
                while index < len(lines) and lines[index].startswith("  "):
                    item.append(lines[index].strip())
                    index += 1
                items.append(" ".join(item))
                if index >= len(lines) or not lines[index].startswith("* "):
                    break
                line = lines[index]
                index += 1
            yield "list", "\n".join(items)
        else:
            paragraph = [line]
            while (
                index < len(lines)
                and lines[index].strip()
                and not lines[index].startswith(("#", "```", "* "))
            ):
                paragraph.append(lines[index])
                index += 1
            yield "paragraph", " ".join(paragraph)


def roff_escape(text):
    text = text.replace("\\", r"\e").replace("-", r"\-")
    if text.startswith((".", "'")):
        text = r"\&" + text
    return text


def roff_inline(text):
    return "".join(
        r"\fB" + roff_escape(part[1:-1]).replace("/", r"/\:") + r"\fR"
        if part.startswith("`")
        else roff_escape(part)
        for part in re.split(r"(`[^`]+`)", text)
    )


def tex_escape(text):
    return text.replace("@", "@@").replace("{", "@{").replace("}", "@}")


def tex_inline(text):
    return "".join(
        "@code{" + tex_escape(part[1:-1]) + "}"
        if part.startswith("`")
        else tex_escape(part)
        for part in re.split(r"(`[^`]+`)", text)
    )


def render_man(content):
    output = [
        r".\" Generated by tools/build_docs.py from docs/cli.md; GPL-3.0-or-later.",
        '.TH OC-BOX 1 "" "oc-box" "User Commands"',
        ".nh",
    ]
    for kind, value in blocks(content):
        if kind == "heading1":
            continue
        if kind.startswith("heading"):
            output.extend(
                [
                    (".SH " if kind == "heading2" else ".SS ")
                    + roff_inline(value.upper() if kind == "heading2" else value)
                ]
            )
        elif kind == "example":
            output.extend(
                [
                    ".PP",
                    ".nf",
                    ".fam C",
                    *(roff_escape(line) for line in value.splitlines()),
                    ".fam T",
                    ".fi",
                ]
            )
        elif kind == "list":
            for item in value.splitlines():
                output.extend([r'.IP "\(bu" 2', roff_inline(item)])
        else:
            output.extend([".PP", roff_inline(value)])
    return "\n".join(output) + "\n"


def render_texinfo(content):
    parsed = list(blocks(content))
    chapters = [value for kind, value in parsed if kind == "heading2"]
    output = [
        r"\input texinfo",
        "@c Generated by tools/build_docs.py from docs/cli.md; GPL-3.0-or-later.",
        "@setfilename oc-box.info",
        "@settitle oc-box command reference",
        "@documentencoding UTF-8",
        "@paragraphindent 0",
        "@dircategory Development",
        "@direntry",
        "* oc-box: (oc-box). Persistent rootless environments for OpenCode.",
        "@end direntry",
        "",
        "@node Top",
        "@top oc-box command reference",
        "",
        "Copyright (C) 2026 Paulo Dias. Licensed GPL-3.0-or-later; see LICENSE and NOTICE.",
        "",
        "@menu",
        *("* " + chapter + "::" for chapter in chapters),
        "@end menu",
        "",
    ]
    for kind, value in parsed:
        if kind == "heading1":
            continue
        if kind == "heading2":
            output.extend(["@node " + value, "@chapter " + tex_inline(value), ""])
        elif kind == "heading3":
            output.extend(["@section " + tex_inline(value), ""])
        elif kind == "example":
            output.extend(["@example", tex_escape(value), "@end example", ""])
        elif kind == "list":
            output.append("@itemize @bullet")
            for item in value.splitlines():
                output.extend(["@item", tex_inline(item)])
            output.extend(["@end itemize", ""])
        else:
            output.extend([tex_inline(value), ""])
    output.append("@bye")
    return "\n".join(output) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify generated man and Texinfo sources without writing files",
    )
    parser.add_argument("--output-dir", type=Path, default=ROOT / "docs")
    args = parser.parse_args(argv)
    content = (ROOT / "docs/cli.md").read_text()
    generated = {
        "oc-box.1": render_man(content),
        "oc-box.texi": render_texinfo(content),
    }
    if args.check:
        stale = [
            name
            for name, value in generated.items()
            if not (args.output_dir / name).is_file()
            or (args.output_dir / name).read_text() != value
        ]
        if stale:
            parser.exit(
                1,
                "Out-of-date generated manuals: "
                + ", ".join(stale)
                + "\nRun python3 tools/build_docs.py\n",
            )
        print("Generated man and Texinfo sources are current.")
        return 0
    makeinfo = shutil.which("makeinfo")
    if makeinfo is None:
        parser.exit(
            1,
            "Building Info requires GNU makeinfo; prebuilt manuals need no build tools to install.\n",
        )
    # Compile before updating any generated files, with stable basenames in the
    # Info header independent of source-checkout or temporary-directory paths.
    with tempfile.TemporaryDirectory(prefix="oc-box-docs-") as temporary:
        work = Path(temporary)
        (work / "oc-box.texi").write_text(generated["oc-box.texi"])
        subprocess.run(
            [makeinfo, "--no-split", "--output=oc-box.info", "oc-box.texi"],
            cwd=work,
            check=True,
            timeout=30,
        )
        info = (work / "oc-box.info").read_bytes()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    for name, value in generated.items():
        (args.output_dir / name).write_text(value)
    (args.output_dir / "oc-box.info").write_bytes(info)
    print("Built oc-box.1, oc-box.texi, and oc-box.info in " + str(args.output_dir))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
